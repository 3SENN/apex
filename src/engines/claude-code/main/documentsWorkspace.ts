// Files and documents on the Claude subscription engine. The API key runs
// document code in Anthropic's container; Claude Code runs it on this
// computer instead, in a private folder per chat under Atelier's data folder:
//
//   <userData>/documents/chats/<chatId>/inputs/   copies of what the person attached
//   <userData>/documents/chats/<chatId>/outputs/  what the model makes for the person
//
// Atelier's own document skills (docx, xlsx, pptx, pdf) load
// as a session-only plugin (`claude --plugin-dir`), since chats run with
// `--setting-sources ''` and never see project or user skills. After each
// reply, new or changed files in outputs/ go to Library › Files and show up
// as 'file-produced' cards, as generated files do on the API key. The folder
// is removed with its chat.

export const DOCUMENTS_FOLDER = 'documents'
export const INPUTS_FOLDER = 'inputs'
export const OUTPUTS_FOLDER = 'outputs'
/** The session-only plugin's name; its skills are `atelier-documents:<skill>`. */
export const DOCUMENTS_PLUGIN_NAME = 'atelier-documents'
/** Claude Code's own tools a documents chat may use, inside its folder only (the launch policy scopes them). */
export const DOCUMENTS_ALLOWED_TOOLS = ['Bash', 'Read', 'Write', 'Edit', 'Skill'] as const
/** Caps on what one reply hands over: a runaway script never floods the Library. */
export const OUTPUT_LIMITS = { files: 20, bytes: 100_000_000 } as const

/** The skills say {brand} where the app's name goes. */
function branded(text: string): string {
  return text.replaceAll('{brand}', BRAND_NAME)
}

/** One local skill per skill the API container loads (documents.ts DOCUMENT_SKILLS), so both engines cover the same files. */
export const DOCUMENT_SKILL_TEXT: Readonly<Record<(typeof DOCUMENT_SKILLS)[number], string>> = {
  docx: branded(docxSkill),
  xlsx: branded(xlsxSkill),
  pptx: branded(pptxSkill),
  pdf: branded(pdfSkill),
}

let root: string | null = null

/** Called once at startup with Atelier's data folder (features/richChat.ts). */
export function configureDocumentsWorkspace(dataDir: string): void {
  root = join(dataDir, DOCUMENTS_FOLDER)
}

/** Where every chat's folder lives. Before configure (tests, scripts), a folder under the system temp dir. */
export function documentsRoot(): string {
  return root ?? join(tmpdir(), 'atelier-documents')
}

const SAFE_ID = /^[A-Za-z0-9_-]{1,128}$/

function chatFolder(chatId: string): string {
  // Chat ids are generated by Atelier; anything else could climb out of the root.
  if (!SAFE_ID.test(chatId)) throw new Error('This chat id can’t name a documents folder.')
  return join(documentsRoot(), 'chats', chatId)
}

/**
 * The chat's private folder, created on demand with its inputs/ and
 * outputs/ folders. Claude Code runs there (cwd and --add-dir) for chats
 * with Files and documents on.
 */
export function documentsWorkspace(chatId: string): string {
  const dir = chatFolder(chatId)
  mkdirSync(join(dir, INPUTS_FOLDER), { recursive: true })
  mkdirSync(join(dir, OUTPUTS_FOLDER), { recursive: true })
  return dir
}

/** The chat's folder when it exists, without creating it. */
export function existingWorkspace(chatId: string): string | null {
  try {
    const dir = chatFolder(chatId)
    return existsSync(dir) ? dir : null
  } catch {
    return null
  }
}

function writeIfChanged(path: string, text: string): void {
  try {
    if (existsSync(path) && readFileSync(path, 'utf8') === text) return
  } catch {
    // Unreadable: write it again.
  }
  writeFileSync(path, text)
}

/**
 * The plugin folder with Atelier's document skills, written (or refreshed when
 * the shipped text changed) on demand. Passed as `--plugin-dir`.
 */
export function documentsPluginDir(): string {
  const dir = join(documentsRoot(), 'plugin')
  mkdirSync(join(dir, '.claude-plugin'), { recursive: true })
  const version = createHash('sha256').update(Object.values(DOCUMENT_SKILL_TEXT).join('\n')).digest('hex').slice(0, 12)
  writeIfChanged(
    join(dir, '.claude-plugin', 'plugin.json'),
    `${JSON.stringify({ name: DOCUMENTS_PLUGIN_NAME, version: `1.0.0+${version}`, description: `${BRAND_NAME}’s document skills: Word, Excel, PowerPoint and PDF files.` }, null, 2)}\n`,
  )
  for (const [name, text] of Object.entries(DOCUMENT_SKILL_TEXT)) {
    mkdirSync(join(dir, 'skills', name), { recursive: true })
    writeIfChanged(join(dir, 'skills', name, 'SKILL.md'), text)
  }
  return dir
}

/** What the system prompt adds for a documents chat on Claude Code (model-facing, not shown to the person). */
export function documentsNote(workspace: string): string {
  return [
    '',
    '',
    '<files_and_documents>',
    `This chat has Files and documents on. Your working folder is ${workspace}. You may run code and read and write files there, and only there.`,
    `- Files the person attaches are copied into ${INPUTS_FOLDER}/. Never change them; save edited copies under new names.`,
    `- Save every file you make for the person (documents, spreadsheets, slides, PDFs, images, data) in ${OUTPUTS_FOLDER}/. When your reply ends, ${BRAND_NAME} hands those files to the person in Library › Files and in the chat. Scripts and scratch files stay outside ${OUTPUTS_FOLDER}/.`,
    `- For Word, Excel, PowerPoint and PDF files, use the ${DOCUMENTS_PLUGIN_NAME} skills (docx, xlsx, pptx, pdf).`,
    '- Mention the files you made by name in your reply; there is no need to print their contents.',
    '</files_and_documents>',
  ].join('\n')
}

export interface DocumentsLaunch {
  /** The chat's folder: Claude Code's cwd. */
  cwd: string
  /** `--add-dir` values. */
  addDirs: string[]
  /** `--plugin-dir` values (the document skills). */
  pluginDirs: string[]
  /** Built-in tools to allow, scoped to `cwd` by the launch policy. */
  allowedTools: readonly string[]
  /** Appended to the system prompt. */
  note: string
}

/** Everything a documents chat's Claude Code launch needs (the launch policy reads it). */
export function documentsLaunch(chatId: string): DocumentsLaunch {
  const cwd = documentsWorkspace(chatId)
  return { cwd, addDirs: [cwd], pluginDirs: [documentsPluginDir()], allowedTools: DOCUMENTS_ALLOWED_TOOLS, note: documentsNote(cwd) }
}

function sameBytes(a: string, b: string): boolean {
  try {
    const sa = statSync(a)
    const sb = statSync(b)
    if (sa.size !== sb.size) return false
    return readFileSync(a).equals(readFileSync(b))
  } catch {
    return false
  }
}

/** A file name that stays inside its folder on every platform. */
export function safeFileName(name: string, fallback = 'file'): string {
  const cleaned = basename(name.replace(/\\/g, '/'))
    .replace(/[\u0000-\u001f<>:"/\\|?*]/g, '_')
    .replace(/^\.+/, '')
    .trim()
    .slice(0, 180)
  return cleaned || fallback
}

/**
 * Copies an attachment into the chat's inputs/ folder and returns its path
 * relative to the folder (`inputs/Report.docx`). The same file sent again
 * (edit, retry) reuses its copy; a different file with the same name gets
 * a numbered name.
 */
export function copyIntoWorkspace(chatId: string, name: string, sourcePath: string): string {
  const inputs = join(documentsWorkspace(chatId), INPUTS_FOLDER)
  const safe = safeFileName(name)
  const ext = extname(safe)
  const stem = ext ? safe.slice(0, -ext.length) : safe
  for (let n = 1; n < 1000; n++) {
    const candidate = n === 1 ? safe : `${stem} (${n})${ext}`
    const target = join(inputs, candidate)
    if (existsSync(target)) {
      if (sameBytes(sourcePath, target)) return `${INPUTS_FOLDER}/${candidate}`
      continue
    }
    copyFileSync(sourcePath, target)
    return `${INPUTS_FOLDER}/${candidate}`
  }
  throw new Error('Too many files with this name in the chat’s folder.')
}

/** outputs/ files by relative path: size and modification time, to tell what a reply made or changed. */
export type OutputSnapshot = ReadonlyMap<string, string>

const SKIPPED_DIRS = new Set(['node_modules', '__pycache__'])

function walk(dir: string, base: string, out: Map<string, { size: number; mtimeMs: number }>, depth = 0): void {
  if (depth > 6) return
  let names: string[]
  try {
    names = readdirSync(dir)
  } catch {
    return
  }
  for (const name of names.sort()) {
    if (name.startsWith('.') || SKIPPED_DIRS.has(name)) continue
    const path = join(dir, name)
    let stat
    try {
      stat = lstatSync(path)
    } catch {
      continue
    }
    // Links could point anywhere on the computer: never follow them.
    if (stat.isSymbolicLink()) continue
    if (stat.isDirectory()) walk(path, base, out, depth + 1)
    else if (stat.isFile()) out.set(relative(base, path).split(sep).join('/'), { size: stat.size, mtimeMs: stat.mtimeMs })
  }
}

function outputFiles(chatId: string): Map<string, { size: number; mtimeMs: number }> {
  const out = new Map<string, { size: number; mtimeMs: number }>()
  const dir = existingWorkspace(chatId)
  if (dir) walk(join(dir, OUTPUTS_FOLDER), join(dir, OUTPUTS_FOLDER), out)
  return out
}

/** Taken before a reply on a documents chat. */
export function snapshotOutputs(chatId: string): OutputSnapshot {
  return new Map([...outputFiles(chatId)].map(([path, s]) => [path, `${s.size}:${s.mtimeMs}`]))
}

/** outputs/ files that are new or changed since the snapshot, in path order, capped. */
export function changedOutputs(chatId: string, before: OutputSnapshot): Array<{ path: string; name: string; size: number }> {
  const dir = existingWorkspace(chatId)
  if (!dir) return []
  const changed: Array<{ path: string; name: string; size: number }> = []
  for (const [rel, s] of outputFiles(chatId)) {
    if (before.get(rel) === `${s.size}:${s.mtimeMs}`) continue
    if (s.size === 0 || s.size > OUTPUT_LIMITS.bytes) continue
    changed.push({ path: join(dir, OUTPUTS_FOLDER, ...rel.split('/')), name: basename(rel), size: s.size })
    if (changed.length >= OUTPUT_LIMITS.files) break
  }
  return changed
}

const OUTPUT_MEDIA: Record<string, string> = {
  docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  pptx: 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
  pdf: 'application/pdf',
  png: 'image/png',
  jpg: 'image/jpeg',
  jpeg: 'image/jpeg',
  gif: 'image/gif',
  webp: 'image/webp',
  svg: 'image/svg+xml',
  csv: 'text/csv',
  tsv: 'text/tab-separated-values',
  md: 'text/markdown',
  txt: 'text/plain',
  json: 'application/json',
  html: 'text/html',
  xml: 'application/xml',
  zip: 'application/zip',
}

/** A media type by extension, for Library › Files. */
export function outputMediaType(name: string): string {
  return OUTPUT_MEDIA[extname(name).slice(1).toLowerCase()] ?? 'application/octet-stream'
}

export interface WorkspaceOutputsContext {
  library: LibraryFiles
  chatId: string
  companionId: string
  /** Each saved file, as it lands (the 'file-produced' event). */
  onFile(file: LibraryFileRef): void
}

/**
 * After a reply: saves what it made in outputs/ to Library › Files, like
 * saveGeneratedFiles does for the API container. A file that fails is
 * logged and skipped.
 */
export function saveWorkspaceOutputs(before: OutputSnapshot, ctx: WorkspaceOutputsContext): LibraryFileRef[] {
  const saved: LibraryFileRef[] = []
  for (const file of changedOutputs(ctx.chatId, before)) {
    try {
      const bytes = readFileSync(file.path)
      const ref = ctx.library.addGenerated({ chatId: ctx.chatId, companionId: ctx.companionId, name: file.name, mediaType: outputMediaType(file.name), bytes })
      saved.push(ref)
      ctx.onFile(ref)
    } catch (err) {
      log.warn('agent', 'Could not save a file from the documents folder', { error: err instanceof Error ? err.message : String(err) })
    }
  }
  return saved
}

/**
 * One reply on the backend: what it saved in outputs/ goes to Library ›
 * Files as file cards, as the API container's files do.
 */
export async function inWorkspace(turn: BackendTurn, run: () => Promise<BackendResult>): Promise<BackendResult> {
  const workspace = beginWorkspaceTurn(turn.chatId, turn.capabilities.documents === true)
  const result = await run()
  workspace?.finish({ library: () => turn.library?.(), companionId: turn.companionId, onFile: (file) => turn.produced?.(file) })
  return result
}

/**
 * One reply's bookkeeping: `begin` before the engine runs, `finish` after.
 * Chats without documents get null and cost nothing.
 */
export function beginWorkspaceTurn(chatId: string, documents: boolean): WorkspaceTurn | null {
  if (!documents) return null
  let before: OutputSnapshot
  try {
    before = snapshotOutputs(chatId)
  } catch {
    return null
  }
  return {
    finish: (ctx) => {
      let library: LibraryFiles | undefined
      try {
        library = ctx.library()
      } catch {
        library = undefined
      }
      // Without Library › Files (tests, early startup) the files stay in the folder for the next reply.
      return library ? saveWorkspaceOutputs(before, { library, chatId, companionId: ctx.companionId, onFile: ctx.onFile }) : []
    },
  }
}

export interface WorkspaceTurn {
  finish(ctx: { library(): LibraryFiles | undefined; companionId: string; onFile(file: LibraryFileRef): void }): LibraryFileRef[]
}

/** Removes the chat's folder with the chat (best effort). */
export function removeDocumentsWorkspace(chatId: string): void {
  const dir = existingWorkspace(chatId)
  if (!dir) return
  try {
    rmSync(dir, { recursive: true, force: true })
  } catch (err) {
    log.warn('agent', 'Could not remove a chat’s documents folder', { error: err instanceof Error ? err.message : String(err) })
  }
}

/** CH-47: a duplicated chat gets its own copy of the folder (the forked session refers to its files). */
export function copyDocumentsWorkspace(fromChatId: string, toChatId: string): void {
  const from = existingWorkspace(fromChatId)
  if (!from) return
  try {
    cpSync(from, chatFolder(toChatId), { recursive: true, errorOnExist: false, filter: (src) => !lstatSync(src).isSymbolicLink() })
  } catch (err) {
    log.warn('agent', 'Could not copy a chat’s documents folder', { error: err instanceof Error ? err.message : String(err) })
  }
}
