// Generates every companion asset: rigs, parts, face layers, configs and the
// manifest, into src/renderer/public/companion/. Deterministic: no clock, no
// unseeded randomness, stable key order. Run with `npm run companion:assets`.

import { createHash } from 'node:crypto'
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildRig } from './lib/build-rig.mjs'
import { CLIPS } from './lib/catalogue.mjs'
import { buildConfigs } from './lib/configs.mjs'
import { faceFiles } from './lib/face-svg.mjs'
import { toGlb } from './lib/gltf.mjs'
import { buildManifest } from './lib/manifest.mjs'
import { buildParts } from './lib/parts.mjs'
import { RIG_DEFS } from './lib/rigs.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(here, '../../src/renderer/public/companion')

function write(rel, data) {
  const path = join(OUT, rel)
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, data)
  return path
}

const json = (value) => `${JSON.stringify(value, null, 2)}\n`

/** The notice that travels with the generated art, into the build and the kit. */
const NOTICE = `# Atelier Companion Art

The files in this folder (the companion parts, rigs, face layers, configuration and presets) are part of the Atelier
Companion Art, generated by \`scripts/companion-assets/\`. They are licensed under the
[Atelier Companion Art License](https://github.com/3SENN/atelier/blob/main/ART-LICENSE.md), not under the Mozilla Public
License that covers Atelier's code.
`

async function main() {
  rmSync(OUT, { recursive: true, force: true })
  const report = []
  const sizeOf = (rel, bytes) => report.push({ rel, bytes: bytes.length, sha: createHash('sha256').update(bytes).digest('hex').slice(0, 12) })

  const rigs = {}
  for (const [rigId, make] of Object.entries(RIG_DEFS)) {
    const rig = make()
    rigs[rigId] = rig
    const bytes = await toGlb(buildRig(rigId, rig, CLIPS))
    write(`rigs/${rigId}.glb`, bytes)
    sizeOf(`rigs/${rigId}.glb`, bytes)
  }

  const parts = buildParts()
  for (const part of parts) {
    const bytes = await toGlb(part.builder)
    write(part.file, bytes)
    sizeOf(part.file, bytes)
  }

  const face = faceFiles()
  for (const [rel, svg] of Object.entries(face.files)) {
    write(rel, svg)
    sizeOf(rel, Buffer.from(svg))
  }

  const configs = buildConfigs({ parts, rigs })
  for (const [rel, value] of Object.entries(configs.files)) {
    const text = json(value)
    write(rel, text)
    sizeOf(rel, Buffer.from(text))
  }

  const manifest = buildManifest({ parts, face, configs })
  write('manifest.json', json(manifest))
  write('LICENSE.md', NOTICE)
  sizeOf('manifest.json', Buffer.from(json(manifest)))

  const total = report.reduce((s, r) => s + r.bytes, 0)
  const digest = createHash('sha256').update(report.map((r) => `${r.rel}:${r.sha}`).join('\n')).digest('hex').slice(0, 16)
  const glbs = report.filter((r) => r.rel.endsWith('.glb'))
  const biggest = [...glbs].sort((a, b) => b.bytes - a.bytes).slice(0, 5)
  console.log(`companion assets: ${report.length} files, ${(total / 1024).toFixed(1)} KB, digest ${digest}`)
  for (const r of biggest) console.log(`  ${r.rel.padEnd(32)} ${(r.bytes / 1024).toFixed(1)} KB`)
  if (process.env.COMPANION_ASSETS_VERBOSE) for (const r of report) console.log(`  ${r.rel} ${r.bytes} ${r.sha}`)
  console.log(`  done in ${process.uptime().toFixed(1)} s`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
